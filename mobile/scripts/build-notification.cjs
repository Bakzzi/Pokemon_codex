'use strict';

// Native notification resources come from the same pinned sprites and XP tables as the game.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const output = path.join(root, 'mobile/android/app/build/generated/notification');
const data = require('../../desktop/data/game-data.json');
for (const dir of ['res/drawable', 'res/drawable-nodpi', 'assets/notification', 'java/io/github/bakzzi/pokemonidle']) {
  fs.mkdirSync(path.join(output, dir), {recursive: true});
}
const entries = [];
const cases = [];
const shinyCases = [];
for (const p of data.pokemon) {
  fs.copyFileSync(path.join(root, `desktop/assets/${p.id}.gif`), path.join(output, `res/drawable-nodpi/partner_raw_${p.id}.gif`));
  fs.writeFileSync(path.join(output, `res/drawable/partner_${p.id}.xml`),
    `<?xml version="1.0" encoding="utf-8"?>\n<animated-image xmlns:android="http://schemas.android.com/apk/res/android" android:src="@drawable/partner_raw_${p.id}" android:autoStart="true" android:repeatCount="-1"/>\n`);
  entries.push([p.id, {name: p.name, growth: p.growth}]);
  cases.push(`            case ${p.id}: return R.drawable.partner_${p.id};`);
  const shiny = path.join(root, `desktop/assets/shiny/${p.id}.gif`);
  if (fs.existsSync(shiny)) {
    fs.copyFileSync(shiny, path.join(output, `res/drawable-nodpi/partner_shiny_raw_${p.id}.gif`));
    fs.writeFileSync(path.join(output, `res/drawable/partner_shiny_${p.id}.xml`),
      `<?xml version="1.0" encoding="utf-8"?>\n<animated-image xmlns:android="http://schemas.android.com/apk/res/android" android:src="@drawable/partner_shiny_raw_${p.id}" android:autoStart="true" android:repeatCount="-1"/>\n`);
    shinyCases.push(`                case ${p.id}: return R.drawable.partner_shiny_${p.id};`);
  }
}
fs.writeFileSync(path.join(output, 'assets/notification/catalog.json'), JSON.stringify({pokemon: Object.fromEntries(entries), experience: data.experience}));
fs.writeFileSync(path.join(output, 'java/io/github/bakzzi/pokemonidle/PartnerSprites.java'),
  `package io.github.bakzzi.pokemonidle;\n\n// Generated by build-notification.cjs; do not edit.\nfinal class PartnerSprites {\n    static int drawable(int id, boolean shiny) {\n        if (shiny) {\n            switch (id) {\n${shinyCases.join('\n')}\n                default: break;\n            }\n        }\n        return drawable(id);\n    }\n    static int drawable(int id) {\n        switch (id) {\n${cases.join('\n')}\n            default: return 0;\n        }\n    }\n}\n`);
console.log(`Notification: ${entries.length} original animated sprites, ${shinyCases.length} alternate sprites and shared XP tables generated.`);
